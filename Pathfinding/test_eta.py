# ==========================================================
# ETA RANKING SUMMARY
# ==========================================================

def _print_change_summary(results):
    """
    Compare candidate ordering and selected route across eta.

    Ranking change and selected-route change are reported
    independently.
    """

    print()
    print("=" * 54)
    print(" ETA EFFECT SUMMARY")
    print("=" * 54)

    previous_eta = None
    previous_signature = None

    ranking_change_count = 0

    for eta, candidates in results:

        signature = _candidate_signature(
            candidates
        )

        if previous_signature is None:

            status = "BASELINE"

        elif signature != previous_signature:

            status = "CHANGED"
            ranking_change_count += 1

        else:

            status = "UNCHANGED"

        print(
            f"eta={eta:.1f} "
            f"status={status:<9} "
            f"count={len(candidates)} "
            f"selected={_selected_path(candidates)}"
        )

        if (
            previous_eta is not None
            and
            signature != previous_signature
        ):

            print(
                f"  ranking changed: "
                f"eta {previous_eta:.1f} "
                f"-> {eta:.1f}"
            )

        previous_eta = eta
        previous_signature = signature

    unique_rankings = {
        _candidate_signature(
            candidates
        )
        for _, candidates in results
    }

    unique_selected = {
        tuple(
            _selected_path(
                candidates
            )
            or []
        )
        for _, candidates in results
    }

    print()

    print(
        f"Number of eta transitions with "
        f"candidate-order change: "
        f"{ranking_change_count}"
    )

    print(
        f"Unique candidate rankings observed: "
        f"{len(unique_rankings)}"
    )

    print(
        f"Unique selected routes observed: "
        f"{len(unique_selected)}"
    )

    print()

    if len(unique_rankings) == 1:

        print(
            "ROUTING DIAGNOSIS: eta did NOT change "
            "the Top-5 candidate ranking for this pair."
        )

    else:

        print(
            "ROUTING DIAGNOSIS: eta DOES change "
            "the Top-5 candidate ranking."
        )

    if len(unique_selected) == 1:

        print(
            "SELECTED ROUTE DIAGNOSIS: "
            "the selected route remained unchanged."
        )

    else:

        print(
            "SELECTED ROUTE DIAGNOSIS: "
            "the selected route changed."
        )

    return {
        "unique_rankings":
            len(unique_rankings),

        "unique_selected":
            len(unique_selected),

        "ranking_change_count":
            ranking_change_count,
    }


# ==========================================================
# FIXED-K CHECK
# ==========================================================

def _check_fixed_k(
    results,
):
    """
    Verify that every eta returns exactly K candidates.

    If this invariant fails, the eta sweep is considered invalid.
    """

    print()
    print("=" * 54)
    print(" FIXED-K CHECK")
    print("=" * 54)

    for eta, candidates in results:

        if len(candidates) != FIXED_K:

            raise AssertionError(
                f"k invariant violated at "
                f"eta={eta:.1f}: "
                f"got {len(candidates)}, "
                f"expected {FIXED_K}"
            )

        print(
            f"eta={eta:.1f}: "
            f"{len(candidates)} candidates "
            f"(K fixed at {FIXED_K})"
        )


# ==========================================================
# FINAL DIAGNOSIS
# ==========================================================

def _print_final_diagnosis(
    sensitivity,
    ranking_summary,
):
    """
    Produce a compact scientific diagnosis.

    Important:
        Ranking stability does NOT imply that eta is ineffective.
        The cost signal can change while the order of the five
        routes remains unchanged.
    """

    print()
    print("=" * 54)
    print(" FINAL ETA DIAGNOSIS")
    print("=" * 54)

    print(
        "eta -> raw heuristic : "
        + (
            "PASS"
            if sensitivity["heuristic_changed"]
            else "FAIL"
        )
    )

    print(
        "eta -> penalty       : "
        + (
            "PASS"
            if sensitivity["penalty_changed"]
            else "FAIL"
        )
    )

    print(
        "eta -> edge cost     : "
        + (
            "PASS"
            if sensitivity["cost_changed"]
            else "FAIL"
        )
    )

    print(
        f"Unique rankings      : "
        f"{ranking_summary['unique_rankings']}"
    )

    print(
        f"Unique selected paths: "
        f"{ranking_summary['unique_selected']}"
    )

    print()

    if not sensitivity["heuristic_changed"]:

        print(
            "RESULT: eta has no observable effect on "
            "the adaptive heuristic for the tested edges."
        )

        print(
            "ACTION: inspect node carbon attributes and "
            "adaptive_heuristic()."
        )

        return

    if not sensitivity["penalty_changed"]:

        print(
            "RESULT: the raw heuristic changes, but the "
            "normalized adaptive penalty does not change."
        )

        print(
            "ACTION: inspect the normalization scale "
            "inside adaptive_penalty()."
        )

        return

    if not sensitivity["cost_changed"]:

        print(
            "RESULT: the adaptive penalty changes, but "
            "the final edge cost does not change."
        )

        print(
            "ACTION: inspect lambda_h and adaptive_edge_cost()."
        )

        return

    if ranking_summary["unique_rankings"] > 1:

        print(
            "RESULT: eta has an observable effect on "
            "the routing objective AND changes Top-K ranking."
        )

    else:

        print(
            "RESULT: eta changes the routing objective, "
            "but Top-K ranking remained stable for this pair."
        )

        print(
            "This is NOT evidence that eta is broken."
        )

        print(
            "The five candidate paths can preserve their "
            "relative ordering even when their costs change."
        )


