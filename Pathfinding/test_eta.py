# Pathfinding/test_eta.py

"""
Diagnostic eta sweep for the adaptive routing criterion.

This test verifies whether eta has an observable effect on the
routing objective before PPO training.

Important invariants:
    - k is ALWAYS fixed at 5.
    - eta is the only swept routing-control parameter.
    - source, destination and payment amount are fixed.
    - max_hops is fixed.
    - lambda_h is fixed.
    - a non-trivial pair with five feasible candidates is selected first.

Diagnostic levels:
    1. eta -> raw adaptive heuristic
    2. eta -> normalized adaptive penalty
    3. eta -> final adaptive edge cost
    4. eta -> candidate path cost
    5. eta -> Top-K ranking
    6. eta -> selected route

Run:
    py -m Pathfinding.test_eta
"""

import math

import networkx as nx
import numpy as np

from Pathfinding.top_k_paths import top_k_paths

from Pathfinding.heuristics import (
    adaptive_heuristic,
    adaptive_penalty,
    adaptive_edge_cost,
    lnd_cost,
)

from RL.test_rl import (
    CONFIG,
    GML_FILENAME,
    load_real_graph,
    prepare_graph,
    prepare_channel_attributes,
)


# ==========================================================
# TEST SETTINGS
# ==========================================================

ETA_VALUES = [
    round(float(x), 1)
    for x in np.arange(
        0.0,
        1.01,
        0.1,
    )
]

# ----------------------------------------------------------
# CRITICAL INVARIANT
# ----------------------------------------------------------

FIXED_K = 5

PAYMENT_AMOUNT = 1000

# Bounded deterministic search for a non-trivial test pair.
PAIR_SOURCE_LIMIT = 40
TARGETS_PER_SOURCE = 8

MIN_SEARCH_HOPS = 2
MAX_SEARCH_HOPS = 6


# ==========================================================
# FORMATTING HELPERS
# ==========================================================

def _fmt(value, digits=6):
    """
    Safe numeric formatter.
    """

    if value is None:
        return "None"

    try:
        value = float(value)

    except (
        TypeError,
        ValueError,
    ):
        return str(value)

    if not math.isfinite(value):
        return "nan"

    return f"{value:.{digits}f}"


# ==========================================================
# PATH SIGNATURE HELPERS
# ==========================================================

def _path_signature(candidate):
    """
    Return a hashable path signature.
    """

    return tuple(
        candidate.get(
            "path",
            [],
        )
    )


def _candidate_signature(candidates):
    """
    Return the ordered Top-K candidate signature.

    Order matters because the purpose of this test is to detect
    changes in candidate ranking.
    """

    return tuple(
        _path_signature(candidate)
        for candidate in candidates
    )


def _selected_path(candidates):
    """
    Return the currently selected candidate.

    top_k_paths() returns candidates ordered by routing cost,
    therefore candidates[0] is the selected route.
    """

    if not candidates:
        return None

    return candidates[0].get(
        "path"
    )


