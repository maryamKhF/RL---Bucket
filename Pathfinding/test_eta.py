# ==========================================================
# TEST-PAIR DISCOVERY
# ==========================================================

def _build_pair_search_graph(G):
    """
    Build a simple directed graph only for discovering
    source/target pairs.

    The actual routing candidates are ALWAYS generated by
    top_k_paths() on the original prepared graph.
    """

    H = nx.DiGraph()

    H.add_nodes_from(
        G.nodes()
    )

    if G.is_multigraph():

        for u, v in G.edges():

            if u == v:
                continue

            if not H.has_edge(
                u,
                v,
            ):
                H.add_edge(
                    u,
                    v,
                )

    else:

        for u, v in G.edges():

            if u == v:
                continue

            H.add_edge(
                u,
                v,
            )

    return H


# ==========================================================
# GENERATE CANDIDATE SOURCE/TARGET PAIRS
# ==========================================================

def _candidate_pairs(G):
    """
    Generate deterministic non-trivial source/target pairs.

    High-degree nodes are tested first.

    Targets must be at least MIN_SEARCH_HOPS away and no farther
    than MAX_SEARCH_HOPS away.
    """

    H = _build_pair_search_graph(
        G
    )

    nodes_by_degree = sorted(
        H.nodes(),
        key=lambda node: (
            -H.degree(node),
            str(node),
        ),
    )

    sources = nodes_by_degree[
        :PAIR_SOURCE_LIMIT
    ]

    for source in sources:

        distances = (
            nx.single_source_shortest_path_length(
                H,
                source,
                cutoff=MAX_SEARCH_HOPS,
            )
        )

        targets = [
            node
            for node, distance in distances.items()
            if (
                node != source
                and
                MIN_SEARCH_HOPS
                <=
                distance
                <=
                MAX_SEARCH_HOPS
            )
        ]

        targets.sort(
            key=lambda node: (
                -H.degree(node),
                distances[node],
                str(node),
            )
        )

        for target in targets[
            :TARGETS_PER_SOURCE
        ]:

            yield (
                source,
                target,
                distances[target],
            )


# ==========================================================
# FIND TEST PAIR
# ==========================================================

def _find_test_pair(
    G,
    amount,
    max_hops,
    lambda_h,
):
    """
    Find one pair satisfying the eta-sweep requirements.

    Requirements:
        1. at least two hops;
        2. at least five feasible candidates at eta=0;
        3. k remains fixed at five.
    """

    print()
    print("=" * 54)
    print(" SEARCH FOR MULTI-CANDIDATE TEST PAIR")
    print("=" * 54)

    print(
        f"Required candidates : {FIXED_K}"
    )

    print(
        f"Payment amount      : {amount}"
    )

    print(
        f"Search hop range    : "
        f"{MIN_SEARCH_HOPS}..{max_hops}"
    )

    tested = 0

    for (
        source,
        target,
        distance,
    ) in _candidate_pairs(G):

        tested += 1

        candidates = top_k_paths(
            G=G,
            source=source,
            target=target,
            amount=amount,
            heuristic_fn=lnd_cost,
            eta=0.0,
            k=FIXED_K,
            max_hops=max_hops,
            lambda_h=lambda_h,
        )

        print(
            f"  Pair {tested:03d}: "
            f"{source} -> {target} "
            f"(unweighted_hops={distance}) "
            f"feasible_candidates="
            f"{len(candidates)}"
        )

        if (
            distance >= MIN_SEARCH_HOPS
            and
            len(candidates) >= FIXED_K
        ):

            print()
            print("FOUND TEST PAIR")

            print(
                f"  source           = {source}"
            )

            print(
                f"  destination      = {target}"
            )

            print(
                f"  unweighted hops  = {distance}"
            )

            print(
                f"  candidates eta=0 = "
                f"{len(candidates)}"
            )

            return (
                source,
                target,
            )

    raise RuntimeError(
        f"Could not find a pair with at least "
        f"{FIXED_K} feasible candidates."
    )


# ==========================================================
# CANDIDATE EDGES
# ==========================================================

def _candidate_edges(candidates):
    """
    Extract unique channel-level edges from candidate paths.
    """

    edges = []
    seen = set()

    for candidate in candidates:

        for edge in candidate.get(
            "edges",
            [],
        ):

            if len(edge) != 3:
                continue

            u, v, key = edge

            signature = (
                u,
                v,
                key,
            )

            if signature in seen:
                continue

            seen.add(
                signature
            )

            edges.append(
                signature
            )

    return edges


# ==========================================================
# READ EDGE DATA
# ==========================================================

def _get_edge_data(
    G,
    u,
    v,
    key,
):
    """
    Read the exact edge data associated with a candidate edge.

    Supports:
        Graph
        DiGraph
        MultiGraph
        MultiDiGraph
    """

    try:

        if G.is_multigraph():

            if key is not None:

                return dict(
                    G[u][v][key]
                )

            data = G[u][v]

            if not data:
                return None

            first_key = next(
                iter(data)
            )

            return dict(
                data[first_key]
            )

        return dict(
            G[u][v]
        )

    except (
        KeyError,
        TypeError,
        AttributeError,
    ):

        return None


# ==========================================================
# HEURISTIC / PENALTY / EDGE-COST SENSITIVITY
# ==========================================================

def _print_heuristic_sensitivity(
    G,
    candidates,
    amount,
    lambda_h,
):
    """
    Isolate:

        eta
          |
          +--> raw heuristic
          |
          +--> normalized penalty
          |
          +--> final adaptive edge cost

    This test does NOT require the final route ranking to change.
    """

    print()
    print("=" * 54)
    print(" ETA -> HEURISTIC -> PENALTY -> EDGE COST")
    print("=" * 54)

    edges = _candidate_edges(
        candidates
    )

    if not edges:

        print(
            "No candidate edges available."
        )

        return {
            "heuristic_changed": False,
            "penalty_changed": False,
            "cost_changed": False,
        }

    any_heuristic_changed = False
    any_penalty_changed = False
    any_cost_changed = False

    # Limit output while preserving deterministic behavior.
    sample_edges = edges[:10]

    print(
        f"Testing {len(sample_edges)} representative "
        f"candidate edges."
    )

    for index, (
        u,
        v,
        key,
    ) in enumerate(
        sample_edges,
        start=1,
    ):

        data = _get_edge_data(
            G,
            u,
            v,
            key,
        )

        if data is None:

            print(
                f"\nedge #{index}: "
                f"({u}, {v}, {key})"
            )

            print(
                "  Could not read edge data."
            )

            continue

        rows = []

        for eta in (
            0.0,
            0.5,
            1.0,
        ):

            raw_h = adaptive_heuristic(
                G,
                u,
                v,
                eta,
            )

            penalty = adaptive_penalty(
                G,
                u,
                v,
                eta,
            )

            edge_info = adaptive_edge_cost(
                G=G,
                u=u,
                v=v,
                data=data,
                amount=amount,
                eta=eta,
                heuristic_fn=lnd_cost,
                lambda_h=lambda_h,
            )

            rows.append(
                {
                    "eta": eta,
                    "raw_h": raw_h,
                    "penalty": penalty,
                    "native_cost": edge_info[
                        "native_cost"
                    ],
                    "cost": edge_info[
                        "cost"
                    ],
                }
            )

        raw_values = [
            row["raw_h"]
            for row in rows
        ]

        penalty_values = [
            row["penalty"]
            for row in rows
        ]

        cost_values = [
            row["cost"]
            for row in rows
        ]

        heuristic_changed = not (
            math.isclose(
                raw_values[0],
                raw_values[1],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
            and
            math.isclose(
                raw_values[1],
                raw_values[2],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
        )

        penalty_changed = not (
            math.isclose(
                penalty_values[0],
                penalty_values[1],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
            and
            math.isclose(
                penalty_values[1],
                penalty_values[2],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
        )

        cost_changed = not (
            math.isclose(
                cost_values[0],
                cost_values[1],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
            and
            math.isclose(
                cost_values[1],
                cost_values[2],
                rel_tol=1e-12,
                abs_tol=1e-12,
            )
        )

        any_heuristic_changed |= (
            heuristic_changed
        )

        any_penalty_changed |= (
            penalty_changed
        )

        any_cost_changed |= (
            cost_changed
        )

        print()
        print(
            f"edge #{index}: "
            f"({u}, {v}, {key})"
        )

        for row in rows:

            print(
                f"  eta={row['eta']:.1f} "
                f"raw_h={_fmt(row['raw_h'])} "
                f"penalty={_fmt(row['penalty'])} "
                f"native={_fmt(row['native_cost'])} "
                f"cost={_fmt(row['cost'])}"
            )

        print(
            "  status: "
            f"heuristic="
            f"{'CHANGED' if heuristic_changed else 'UNCHANGED'}, "
            f"penalty="
            f"{'CHANGED' if penalty_changed else 'UNCHANGED'}, "
            f"cost="
            f"{'CHANGED' if cost_changed else 'UNCHANGED'}"
        )

    print()
    print("-" * 54)

    print(
        "HEURISTIC EFFECT : "
        + (
            "CHANGED"
            if any_heuristic_changed
            else "UNCHANGED"
        )
    )

    print(
        "PENALTY EFFECT   : "
        + (
            "CHANGED"
            if any_penalty_changed
            else "UNCHANGED"
        )
    )

    print(
        "EDGE COST EFFECT : "
        + (
            "CHANGED"
            if any_cost_changed
            else "UNCHANGED"
        )
    )

    return {
        "heuristic_changed":
            any_heuristic_changed,

        "penalty_changed":
            any_penalty_changed,

        "cost_changed":
            any_cost_changed,
    }


